-- ---------------------------------------------------------------------------
-- 2. Foreign keys → ON DELETE CASCADE.
--
--    Done as a sweep rather than a list of hand-written ALTERs because the
--    schema was generated by Lovable and the constraint names are not
--    predictable. The sweep finds every single-column FK pointing at one of
--    the parent tables and rewrites it in place, keeping the existing name.
--
--    It is a no-op for any constraint that already has the right action, so
--    re-running this file costs nothing.
-- ---------------------------------------------------------------------------
DO $$
DECLARE
  -- Deleting one of these must not be blocked by anything below it.
  parents CONSTANT TEXT[] := ARRAY[
    'properties', 'apartments', 'issues', 'inspections', 'projects',
    'property_objects', 'logbook_entries'
  ];

  -- Exceptions: child.column pairs where the child OUTLIVES the parent and
  -- only loses the link. Everything not listed here cascades.
  --   contacts.property_id          — an entreprenör is not owned by a building;
  --                                   they may be ansvarig in several. Also,
  --                                   deleting the contact row would break
  --                                   issues.assigned_contact_id elsewhere.
  --   property_objects.apartment_id — a hiss/tvättstuga belongs to the
  --                                   building; the apartment link is optional
  --                                   (see the objekt notes in CLAUDE.md).
  --   *.property_object_id          — an ärende or loggbok row describing an
  --                                   objekt is still a real record once the
  --                                   objekt is gone.
  set_null CONSTANT TEXT[] := ARRAY[
    'contacts.property_id',
    'property_objects.apartment_id',
    'issues.property_object_id',
    'inspections.property_object_id',
    'logbook_entries.property_object_id'
  ];

  r         RECORD;
  v_action  TEXT;
  v_current TEXT;
  v_notnull BOOLEAN;
  v_changed INT := 0;
BEGIN
  FOR r IN
    SELECT con.oid         AS conoid,
           con.conname     AS conname,
           con.confdeltype AS confdeltype,
           src.relname     AS child_table,
           att.attname     AS child_column,
           att.attnotnull  AS child_notnull,
           tgt.relname     AS parent_table
    FROM pg_constraint con
    JOIN pg_class     src ON src.oid = con.conrelid
    JOIN pg_class     tgt ON tgt.oid = con.confrelid
    JOIN pg_namespace ns  ON ns.oid  = src.relnamespace
    JOIN pg_attribute att ON att.attrelid = con.conrelid
                         AND att.attnum   = con.conkey[1]
    WHERE con.contype = 'f'
      AND ns.nspname  = 'public'
      AND tgt.relname = ANY (parents)
      AND array_length(con.conkey, 1) = 1     -- composite FKs: none exist, and
                                              -- rewriting one blind is unsafe
    ORDER BY src.relname, att.attname
  LOOP
    v_notnull := r.child_notnull;

    IF (r.child_table || '.' || r.child_column) = ANY (set_null) THEN
      -- SET NULL on a NOT NULL column raises at delete time, not now, so the
      -- failure would surface as a mystery 23502 much later. Fall back.
      v_action := CASE WHEN v_notnull THEN 'CASCADE' ELSE 'SET NULL' END;
      IF v_notnull THEN
        RAISE NOTICE '%.% is NOT NULL — cascading instead of SET NULL',
          r.child_table, r.child_column;
      END IF;
    ELSE
      v_action := 'CASCADE';
    END IF;

    v_current := CASE r.confdeltype
                   WHEN 'c' THEN 'CASCADE'
                   WHEN 'n' THEN 'SET NULL'
                   WHEN 'd' THEN 'SET DEFAULT'
                   WHEN 'r' THEN 'RESTRICT'
                   ELSE 'NO ACTION'
                 END;

    CONTINUE WHEN v_current = v_action;

    EXECUTE format('ALTER TABLE public.%I DROP CONSTRAINT %I',
                   r.child_table, r.conname);
    EXECUTE format(
      'ALTER TABLE public.%I ADD CONSTRAINT %I FOREIGN KEY (%I) '
      'REFERENCES public.%I(id) ON DELETE %s',
      r.child_table, r.conname, r.child_column, r.parent_table, v_action);

    v_changed := v_changed + 1;
    RAISE NOTICE '% (%.% -> %): % -> %',
      r.conname, r.child_table, r.child_column, r.parent_table,
      v_current, v_action;
  END LOOP;

  RAISE NOTICE '% foreign key(s) rewritten.', v_changed;
END $$;


-- ---------------------------------------------------------------------------
-- 3. Admin DELETE policies.
--
--    Two rules, both load-bearing:
--
--    a) RLS is NEVER enabled here. A table with RLS off today is protected by
--       grants alone; switching it on while adding only a DELETE policy would
--       deny SELECT/INSERT/UPDATE to everyone and take the app down. The loop
--       therefore adds a policy only where RLS is already on, and otherwise
--       just makes sure the DELETE grant exists.
--
--    b) The policy is `is_admin()` and nothing else. Styrelse is read-only by
--       spec and an entreprenör must never be able to erase an ärende they
--       were assigned. Deletion is admin-only everywhere in this app, which is
--       also what <DeleteButton> and the loggbok toolbar assume client-side —
--       keep the two in agreement.
-- ---------------------------------------------------------------------------
DO $$
DECLARE
  tables CONSTANT TEXT[] := ARRAY[
    -- the five the client asked for
    'properties', 'apartments', 'issues', 'inspections', 'projects',
    -- loggbok
    'logbook_entries', 'logbook_comments',
    -- children reachable through a cascade, and deletable in their own right
    'property_objects', 'documents', 'property_history', 'actions',
    'issue_images', 'project_images', 'issue_comments', 'issue_status_history',
    'protocols', 'inspection_protocols', 'budget_items', 'property_budgets',
    -- Historik. See the note below — this reverses an earlier decision.
    'audit_events'
  ];
  t       TEXT;
  v_rls   BOOLEAN;
  v_pol   TEXT;
BEGIN
  FOREACH t IN ARRAY tables LOOP
    SELECT c.relrowsecurity INTO v_rls
    FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace
    WHERE n.nspname = 'public' AND c.relname = t AND c.relkind = 'r';

    IF NOT FOUND THEN
      RAISE NOTICE 'skip % — no such table', t;
      CONTINUE;
    END IF;

    EXECUTE format('GRANT DELETE ON public.%I TO authenticated', t);

    IF NOT v_rls THEN
      RAISE NOTICE '% — RLS off, grant only (deliberately not enabling RLS)', t;
      CONTINUE;
    END IF;

    v_pol := t || '_delete_admin';
    EXECUTE format('DROP POLICY IF EXISTS %I ON public.%I', v_pol, t);
    EXECUTE format(
      'CREATE POLICY %I ON public.%I FOR DELETE TO authenticated USING (is_admin())',
      v_pol, t);
    RAISE NOTICE '% — policy % created', t, v_pol;
  END LOOP;
END $$;

-- audit_events: this is a deliberate reversal, recorded so the next reader
-- does not "fix" it back.
--
-- audit-events.sql argues an audit log an admin can edit is not an audit log,
-- and revoked INSERT/UPDATE/DELETE from `authenticated` accordingly. The client
-- overrode that on 2026-07-27: admin must be able to clear Historik, selected
-- rows or all of it, leaving no tombstone.
--
-- What is preserved: INSERT and UPDATE stay revoked. A row still cannot be
-- fabricated or rewritten from the client — only removed. So an entry that
-- exists is still trustworthy; the log is just no longer guaranteed complete.
DO $$
BEGIN
  IF EXISTS (SELECT 1 FROM pg_tables
             WHERE schemaname = 'public' AND tablename = 'audit_events') THEN
    REVOKE INSERT, UPDATE ON audit_events FROM authenticated;
  ELSE
    RAISE NOTICE 'audit_events missing — run audit-events.sql first.';
  END IF;
END $$;


