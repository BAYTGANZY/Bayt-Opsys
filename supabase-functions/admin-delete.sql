-- ============================================================================
-- admin-delete.sql — make "Radera" actually work for admin.
--
-- Run by hand in the Supabase SQL editor. Not part of the Vite build.
-- Safe to re-run in full: every step skips work that is already done.
--
-- ---------------------------------------------------------------------------
-- THE PROBLEM THIS SOLVES
--
-- <DeleteButton> has existed on all five detail pages (fastighet, lägenhet,
-- felanmälan, besiktning, projekt) for a while, and it already renders only
-- for admin. It nonetheless failed in practice for two independent reasons:
--
--   1. FOREIGN KEYS. Child rows were created with the PostgREST default
--      (NO ACTION), so deleting a fastighet that still has lägenheter,
--      ärenden, dokument or loggbok rows raises 23503 and the button shows
--      "Kan inte raderas — det finns kopplad data kvar". A building with any
--      history at all could therefore never be deleted.
--
--   2. RLS. Several tables have row level security on with SELECT/INSERT/
--      UPDATE policies but no DELETE policy. Postgres denies what no policy
--      permits, so `.delete()` returned 0 rows and the UI reported success
--      while nothing was removed — the worst of the two failure modes.
--
-- Step 2 fixes the first, step 3 the second.
--
-- ---------------------------------------------------------------------------
-- PRODUCT DECISION ENCODED HERE (client, 2026-07-27): CASCADE.
--
-- Deleting a fastighet deletes everything under it — lägenheter, felanmälningar,
-- besiktningar, projekt, objekt, dokument, loggbok, åtgärder. Deleting a
-- lägenhet deletes its ärenden and loggbok. This is not recoverable from the
-- UI; the confirm dialog in DeleteButton.tsx names the counts before it runs.
--
-- audit_events is deliberately NOT part of any cascade — it has no foreign
-- keys at all (see the header of audit-events.sql: "an audit trail must
-- outlive the thing it describes"), so a cascade leaves the Historik intact.
-- Admins clear Historik explicitly instead, via the multi-select toolbar —
-- see step 3's note on audit_events.
-- ============================================================================


-- ---------------------------------------------------------------------------
-- 1. PREFLIGHT — READ-ONLY. Run this first and read the output.
--    is_admin() is created by hand in the dashboard and has no DDL in this
--    repo. Nothing below works without it. Expect has_is_admin = true.
-- ---------------------------------------------------------------------------
SELECT
  EXISTS (SELECT 1 FROM pg_proc WHERE proname = 'is_admin') AS has_is_admin;

