-- 4a. Every FK into a parent table and what it now does on delete.
--     Expect 'CASCADE' everywhere except the five SET NULL exceptions.
SELECT src.relname  AS child_table,
       att.attname  AS child_column,
       tgt.relname  AS parent_table,
       CASE con.confdeltype
         WHEN 'c' THEN 'CASCADE' WHEN 'n' THEN 'SET NULL'
         WHEN 'd' THEN 'SET DEFAULT' WHEN 'r' THEN 'RESTRICT'
         ELSE 'NO ACTION' END AS on_delete
FROM pg_constraint con
JOIN pg_class     src ON src.oid = con.conrelid
JOIN pg_class     tgt ON tgt.oid = con.confrelid
JOIN pg_namespace ns  ON ns.oid  = src.relnamespace
JOIN pg_attribute att ON att.attrelid = con.conrelid AND att.attnum = con.conkey[1]
WHERE con.contype = 'f' AND ns.nspname = 'public'
  AND tgt.relname IN ('properties','apartments','issues','inspections',
                      'projects','property_objects','logbook_entries')
ORDER BY 3, 1, 2;

-- 4b. The DELETE policies.
SELECT tablename, policyname, qual
FROM pg_policies
WHERE schemaname = 'public' AND cmd = 'DELETE'
ORDER BY tablename;

-- 4c. Tables that still have RLS on but NO delete policy — anything listed
--     here will silently delete zero rows from the client.
SELECT c.relname AS table_without_delete_policy
FROM pg_class c
JOIN pg_namespace n ON n.oid = c.relnamespace
WHERE n.nspname = 'public' AND c.relkind = 'r' AND c.relrowsecurity
  AND c.relname IN ('properties','apartments','issues','inspections','projects',
                    'logbook_entries','logbook_comments','property_objects',
                    'documents','property_history','audit_events')
  AND NOT EXISTS (
    SELECT 1 FROM pg_policies p
    WHERE p.schemaname = 'public' AND p.tablename = c.relname AND p.cmd = 'DELETE')
ORDER BY 1;


